#!/usr/bin/env python3
"""Keep the native dependency diagram in docs/native-libraries.md generated from the code.

The Mermaid block between the `native-graph:begin` and `native-graph:end` markers is rendered from
LIBRARY_DEPS and CONSUMER_DEPS in tools/ci/check_native_includes.py, the same table the include
check enforces and that mirrors the target_link_libraries lines in core/CMakeLists.txt. Editing the
table is the only way to change the diagram; CI fails while the committed block is stale.

    python3 tools/ci/native_graph_doc.py             # rewrite the block in docs/native-libraries.md
    python3 tools/ci/native_graph_doc.py --check     # CI: fail when the committed block is stale
    python3 tools/ci/native_graph_doc.py --self-test # prove the check catches a stale block
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_native_includes import CONSUMER_DEPS, LIBRARY_DEPS  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "native-libraries.md"
BEGIN = "<!-- native-graph:begin -->"
END = "<!-- native-graph:end -->"
NOTE = (
    "<!-- Generated by tools/ci/native_graph_doc.py from LIBRARY_DEPS in tools/ci/check_native_includes.py."
    " Edit the table, run the script, commit both. CI fails while this block is stale. -->"
)
# Libraries whose only dependencies are outside LIBRARY_DEPS (third-party), named in their label.
EXTERNAL_ONLY = {"library": "TagLib only"}
CONSUMER_LABELS = {"tests": "host tests (pure parts)", "jni": "JNI layer (app/src/main/cpp)"}


def layer_of(deps: dict[str, set[str]]) -> dict[str, int]:
    """Each library's layer: 0 with no in-repo dependencies, else one above its highest dependency."""
    layers: dict[str, int] = {}

    def layer(lib: str, trail: tuple[str, ...]) -> int:
        if lib in trail:
            raise ValueError("cycle: " + " -> ".join(trail + (lib,)))
        if lib not in layers:
            layers[lib] = 0 if not deps[lib] else 1 + max(layer(d, trail + (lib,)) for d in sorted(deps[lib]))
        return layers[lib]

    for lib in sorted(deps):
        layer(lib, ())
    return layers


def render() -> str:
    layers = layer_of(LIBRARY_DEPS)
    lines = ["```mermaid", "graph TD"]
    for n in sorted(set(layers.values()), reverse=True):
        lines.append(f'  subgraph layer{n}["layer {n}"]')
        for lib in sorted(l for l, k in layers.items() if k == n):
            label = f"geode_{lib}" + (f" ({EXTERNAL_ONLY[lib]})" if lib in EXTERNAL_ONLY else "")
            lines.append(f'    {lib}["{label}"]')
        lines.append("  end")
    lines.append('  subgraph consumers["consumers (not libraries)"]')
    for consumer in sorted(CONSUMER_DEPS):
        lines.append(f'    {consumer}["{CONSUMER_LABELS.get(consumer, consumer)}"]')
    lines.append("  end")
    for lib in sorted(LIBRARY_DEPS):
        for dep in sorted(LIBRARY_DEPS[lib]):
            lines.append(f"  {lib} --> {dep}")
    for consumer in sorted(CONSUMER_DEPS):
        for dep in sorted(CONSUMER_DEPS[consumer]):
            lines.append(f"  {consumer} -.-> {dep}")
    lines.append("```")
    return "\n".join([BEGIN, NOTE, *lines, END])


def replace_block(doc: str, block: str) -> str:
    start = doc.find(BEGIN)
    end = doc.find(END)
    if start < 0 or end < 0 or end < start:
        raise ValueError(f"{DOC.relative_to(ROOT)} has no {BEGIN} ... {END} block")
    return doc[:start] + block + doc[end + len(END):]


def check(doc: str) -> list[str]:
    try:
        expected = replace_block(doc, render())
    except ValueError as error:
        return [str(error)]
    if expected != doc:
        return [f"{DOC.relative_to(ROOT)}: the native dependency diagram is stale; run tools/ci/native_graph_doc.py"]
    return []


def self_test() -> bool:
    current = replace_block(DOC.read_text(encoding="utf-8"), render())
    cases = {
        "current block passes": (current, False),
        "an edited edge fails": (current.replace("  bridge --> api_types\n", "  bridge --> util\n"), True),
        "a dropped node fails": (current.replace('    util["geode_util"]\n', ""), True),
        "missing markers fail": (current.replace(BEGIN, "").replace(END, ""), True),
    }
    ok = True
    for name, (doc, should_fail) in cases.items():
        failed = bool(check(doc))
        status = "ok" if failed == should_fail else "FAILED"
        ok &= failed == should_fail
        print(f"  {status}: {name}")
    print("self-test " + ("passed" if ok else "FAILED"))
    return ok


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return 0 if self_test() else 1
    doc = DOC.read_text(encoding="utf-8")
    if "--check" in argv:
        problems = check(doc)
        for problem in problems:
            print(problem)
        print("native dependency diagram " + ("is current" if not problems else "is STALE"))
        return 1 if problems else 0
    updated = replace_block(doc, render())
    if updated != doc:
        DOC.write_text(updated, encoding="utf-8")
        print(f"updated {DOC.relative_to(ROOT)}")
    else:
        print(f"{DOC.relative_to(ROOT)} already current")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
