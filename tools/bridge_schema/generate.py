#!/usr/bin/env python3
"""Generate the native bridge's C, C++ and Kotlin types from core/bridge/schema/native_bridge.json.

The schema is the one place the snapshot's wire format and the bridge's status codes are written
down (ADR-0005, Native code), so Kotlin and C++ cannot drift. This script writes:

- core/api/include/geode/api/geode_status.h                       GeodeStatus, the C ABI's status codes
- core/bridge/include/geode/bridge/CustomizationSnapshot.hpp      the C++ snapshot type and its constants
- core/bridge/CustomizationSnapshot.cpp                           the C++ decoder and encoder
- engine/audio-core/.../bridge/NativeStatus.kt                    the Kotlin status enum
- engine/audio-core/.../bridge/CustomizationSnapshot.kt           the Kotlin snapshot type and its encoder

    python3 tools/bridge_schema/generate.py           # rewrite the generated files
    python3 tools/bridge_schema/generate.py --check   # CI: fail when a generated file is stale

Wire format (little-endian): a header of magic (u32), version (u16), reserved (u16, always 0) and
payload length (u32), then every field in schema order. bool is one byte (0 or 1), u32 four bytes,
f32 an IEEE-754 float; an array is its elements back to back. The reader rejects anything else.
"""

from __future__ import annotations

import json
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SCHEMA = ROOT / "core/bridge/schema/native_bridge.json"
KOTLIN_DIR = "engine/audio-core/src/main/kotlin/dev/geode/engine/bridge"
HEADER_BYTES = 12
TYPE_BYTES = {"bool": 1, "u32": 4, "f32": 4}
CPP_TYPES = {"bool": "bool", "u32": "uint32_t", "f32": "float"}
CPP_DEFAULTS = {"bool": "false", "u32": "0", "f32": "0.0f"}
KOTLIN_TYPES = {"bool": "Boolean", "u32": "Int", "f32": "Float"}
GENERATED = "Generated by tools/bridge_schema/generate.py from core/bridge/schema/native_bridge.json. Do not edit."
KOTLIN_GENERATED = [
    "// Generated by tools/bridge_schema/generate.py",
    "// from core/bridge/schema/native_bridge.json. Do not edit.",
]
# ktlint's line limit for the Kotlin code style this repository uses.
KOTLIN_LINE = 100


def kdoc(text: str, indent: str) -> list[str]:
    """A KDoc comment, on one line when it fits and wrapped to the Kotlin line limit when not."""
    one = f"{indent}/** {text} */"
    if len(one) <= KOTLIN_LINE:
        return [one]
    body = textwrap.wrap(text, KOTLIN_LINE - len(indent) - 3)
    return [f"{indent}/**"] + [f"{indent} * {line}" for line in body] + [f"{indent} */"]


def snake_upper(name: str) -> str:
    out = []
    for ch in name:
        if ch.isupper() and out:
            out.append("_")
        out.append(ch.upper())
    return "".join(out)


def pascal(name: str) -> str:
    return name[0].upper() + name[1:]


def magic_value(magic: str) -> int:
    raw = magic.encode("ascii")
    if len(raw) != 4:
        raise SystemExit("snapshot magic must be four ASCII characters")
    return int.from_bytes(raw, "little")


def payload_bytes(fields: list[dict]) -> int:
    return sum(TYPE_BYTES[f["type"]] * f.get("count", 1) for f in fields)


def status_header(schema: dict) -> str:
    lines = [
        f"/* {GENERATED} */",
        "#pragma once",
        "",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
        "",
        "/* What every native bridge call reports. Kotlin maps each one to a named failure (NativeStatus.kt). */",
        "typedef enum GeodeStatus {",
    ]
    for code, status in enumerate(schema["statuses"]):
        lines.append(f"    GEODE_STATUS_{status['name']} = {code}, /* {status['doc']} */")
    lines += [
        f"    GEODE_STATUS_COUNT = {len(schema['statuses'])}",
        "} GeodeStatus;",
        "",
        "#ifdef __cplusplus",
        "}",
        "#endif",
        "",
    ]
    return "\n".join(lines)


def snapshot_header(schema: dict) -> str:
    snap = schema["snapshot"]
    fields = snap["fields"]
    payload = payload_bytes(fields)
    lines = [
        f"// {GENERATED}",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <span>",
        "",
        '#include "geode/api/geode_status.h"',
        "",
        "namespace geode::bridge {",
        "",
        f"inline constexpr uint32_t kSnapshotMagic = 0x{magic_value(snap['magic']):08X}u;  // \"{snap['magic']}\"",
        f"inline constexpr uint16_t kSnapshotVersion = {snap['version']};",
        f"inline constexpr size_t kSnapshotHeaderBytes = {HEADER_BYTES};",
        f"inline constexpr size_t kSnapshotPayloadBytes = {payload};",
        f"inline constexpr size_t kSnapshotWireBytes = kSnapshotHeaderBytes + kSnapshotPayloadBytes;",
    ]
    for f in fields:
        if "count" in f:
            lines.append(f"inline constexpr size_t kSnapshot{pascal(f['name'])}Count = {f['count']};")
    lines += ["", f"// {snap['doc']}", f"struct {snap['name']} {{"]
    for f in fields:
        lines.append(f"    // {f['doc']}")
        if "count" in f:
            lines.append(f"    std::array<{CPP_TYPES[f['type']]}, kSnapshot{pascal(f['name'])}Count> {f['name']}{{}};")
        else:
            lines.append(f"    {CPP_TYPES[f['type']]} {f['name']} = {CPP_DEFAULTS[f['type']]};")
    lines += [
        "",
        f"    bool operator==(const {snap['name']}&) const = default;",
        "};",
        "",
        "// Reads one snapshot. On GEODE_STATUS_OK `out` holds it; on any other status `out` is untouched.",
        f"GeodeStatus decodeSnapshot(std::span<const uint8_t> wire, {snap['name']}& out) noexcept;",
        "// Writes one snapshot and returns the bytes written: kSnapshotWireBytes, or 0 when `wire` is too small.",
        f"size_t encodeSnapshot(const {snap['name']}& snapshot, std::span<uint8_t> wire) noexcept;",
        "",
        "}  // namespace geode::bridge",
        "",
    ]
    return "\n".join(lines)


def snapshot_source(schema: dict) -> str:
    snap = schema["snapshot"]
    name = snap["name"]
    lines = [
        f"// {GENERATED}",
        '#include "geode/bridge/CustomizationSnapshot.hpp"',
        "",
        '#include "Wire.hpp"',
        "",
        "namespace geode::bridge {",
        "",
        f"GeodeStatus decodeSnapshot(std::span<const uint8_t> wire, {name}& out) noexcept {{",
        "    if (wire.size() < kSnapshotHeaderBytes) return GEODE_STATUS_MALFORMED_SNAPSHOT;",
        "    wire::Reader in(wire);",
        "    if (in.u32() != kSnapshotMagic) return GEODE_STATUS_MALFORMED_SNAPSHOT;",
        "    if (in.u16() != kSnapshotVersion) return GEODE_STATUS_UNSUPPORTED_VERSION;",
        "    if (in.u16() != 0) return GEODE_STATUS_MALFORMED_SNAPSHOT;",
        "    if (in.u32() != kSnapshotPayloadBytes) return GEODE_STATUS_MALFORMED_SNAPSHOT;",
        "    if (in.remaining() != kSnapshotPayloadBytes) return GEODE_STATUS_MALFORMED_SNAPSHOT;",
        f"    {name} decoded;",
    ]
    for f in snap["fields"]:
        n = f["name"]
        if f["type"] == "u32":
            lines.append(f"    decoded.{n} = in.u32();")
        elif f["type"] == "bool":
            lines.append(f"    if (!wire::readFlag(in, decoded.{n})) return GEODE_STATUS_MALFORMED_SNAPSHOT;")
        elif "count" in f:
            lines.append(f"    if (!wire::readFinite(in, std::span<float>(decoded.{n}))) return GEODE_STATUS_INVALID_ARGUMENT;")
        else:
            lines.append(f"    if (!wire::readFinite(in, decoded.{n})) return GEODE_STATUS_INVALID_ARGUMENT;")
    lines += [
        "    out = decoded;",
        "    return GEODE_STATUS_OK;",
        "}",
        "",
        f"size_t encodeSnapshot(const {name}& snapshot, std::span<uint8_t> wire) noexcept {{",
        "    if (wire.size() < kSnapshotWireBytes) return 0;",
        "    wire::Writer out(wire);",
        "    out.u32(kSnapshotMagic);",
        "    out.u16(kSnapshotVersion);",
        "    out.u16(0);",
        "    out.u32(static_cast<uint32_t>(kSnapshotPayloadBytes));",
    ]
    for f in snap["fields"]:
        n = f["name"]
        if f["type"] == "u32":
            lines.append(f"    out.u32(snapshot.{n});")
        elif f["type"] == "bool":
            lines.append(f"    out.u8(snapshot.{n} ? 1 : 0);")
        elif "count" in f:
            lines.append(f"    for (const float value : snapshot.{n}) out.f32(value);")
        else:
            lines.append(f"    out.f32(snapshot.{n});")
    lines += [
        "    return out.written();",
        "}",
        "",
        "}  // namespace geode::bridge",
        "",
    ]
    return "\n".join(lines)


def kotlin_status(schema: dict) -> str:
    lines = KOTLIN_GENERATED + [
        "package dev.geode.engine.bridge",
        "",
        *kdoc("What every native bridge call reports: GeodeStatus in geode/api/geode_status.h, code for code.", ""),
        "enum class NativeStatus(",
        "    val code: Int,",
        ") {",
    ]
    for code, status in enumerate(schema["statuses"]):
        lines += kdoc(status["doc"], "    ")
        lines.append(f"    {status['name']}({code}),")
        lines.append("")
    lines[-1] = "    ;"
    lines += [
        "",
        "    companion object {",
        "        /** The status with this [code], or null for a code this schema does not know. */",
        "        fun of(code: Int): NativeStatus? = entries.firstOrNull { it.code == code }",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def kotlin_snapshot(schema: dict) -> str:
    snap = schema["snapshot"]
    name = snap["name"]
    fields = snap["fields"]
    lines = KOTLIN_GENERATED + [
        "package dev.geode.engine.bridge",
        "",
        "import java.nio.ByteBuffer",
        "import java.nio.ByteOrder",
        "",
        *kdoc(snap["doc"], ""),
        f"data class {name}(",
    ]
    for f in fields:
        kotlin_type = KOTLIN_TYPES[f["type"]]
        if "count" in f:
            kotlin_type = f"List<{kotlin_type}>"
        lines += kdoc(f["doc"], "    ")
        lines.append(f"    val {f['name']}: {kotlin_type},")
    lines.append(") {")
    lines.append("    init {")
    for f in fields:
        if f["type"] == "u32":
            lines.append(f'        require({f["name"]} >= 0) {{ "{f["name"]} must not be negative, got ${f["name"]}" }}')
        if "count" in f:
            const = f"{snake_upper(f['name'])}_COUNT"
            n = f["name"]
            lines.append(f'        require({n}.size == {const}) {{ "{n}: ${{{n}.size}} of ${const}" }}')
    lines += [
        "    }",
        "",
        "    /** The snapshot in the schema's wire format, ready for the bridge. */",
        "    fun encode(): ByteArray {",
        "        val out = ByteBuffer.allocate(WIRE_BYTES).order(ByteOrder.LITTLE_ENDIAN)",
        "        out.putInt(MAGIC)",
        "        out.putShort(VERSION)",
        "        out.putShort(RESERVED)",
        "        out.putInt(PAYLOAD_BYTES)",
    ]
    for f in fields:
        n = f["name"]
        if f["type"] == "u32":
            lines.append(f"        out.putInt({n})")
        elif f["type"] == "bool":
            lines.append(f"        out.put(if ({n}) FLAG_ON else FLAG_OFF)")
        elif "count" in f:
            lines.append(f"        {n}.forEach {{ out.putFloat(it) }}")
        else:
            lines.append(f"        out.putFloat({n})")
    lines += [
        "        return out.array()",
        "    }",
        "",
        "    companion object {",
        f"        /** \"{snap['magic']}\", the first four bytes of every snapshot. */",
        f"        const val MAGIC: Int = 0x{magic_value(snap['magic']):08X}",
        f"        const val VERSION: Short = {snap['version']}",
        f"        const val HEADER_BYTES: Int = {HEADER_BYTES}",
        f"        const val PAYLOAD_BYTES: Int = {payload_bytes(fields)}",
        "        const val WIRE_BYTES: Int = HEADER_BYTES + PAYLOAD_BYTES",
    ]
    for f in fields:
        if "count" in f:
            lines.append(f"        const val {snake_upper(f['name'])}_COUNT: Int = {f['count']}")
    lines += [
        "        private const val RESERVED: Short = 0",
        "        private const val FLAG_ON: Byte = 1",
        "        private const val FLAG_OFF: Byte = 0",
        "    }",
        "}",
        "",
    ]
    return "\n".join(lines)


def outputs(schema: dict) -> dict[str, str]:
    return {
        "core/api/include/geode/api/geode_status.h": status_header(schema),
        "core/bridge/include/geode/bridge/CustomizationSnapshot.hpp": snapshot_header(schema),
        "core/bridge/CustomizationSnapshot.cpp": snapshot_source(schema),
        f"{KOTLIN_DIR}/NativeStatus.kt": kotlin_status(schema),
        f"{KOTLIN_DIR}/CustomizationSnapshot.kt": kotlin_snapshot(schema),
    }


def main(argv: list[str]) -> int:
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    stale = []
    for rel, text in outputs(schema).items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == text:
            continue
        if "--check" in argv:
            stale.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {rel}")
    for rel in stale:
        print(f"::error file={rel}::stale: run python3 tools/bridge_schema/generate.py and commit the result")
    if stale:
        print(f"{len(stale)} generated file(s) out of date with {SCHEMA.relative_to(ROOT)}", file=sys.stderr)
        return 1
    if "--check" in argv:
        print("bridge schema: every generated file matches core/bridge/schema/native_bridge.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
